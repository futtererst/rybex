const artifact = (
  id: string,
  name: string,
  status: GateArtifact["status"],
  owner: string,
  dueDate?: string
): GateArtifact => ({
  id,
  name,
  status,
  owner,
  dueDate
});

const readiness = (artifacts: GateArtifact[]) =>
  Math.round(
    (artifacts.filter((item) => item.status === "complete" || item.status === "waived")
      .length /
      artifacts.length) *
      100
  );

const makeGate = (
  projectId: string,
  phaseId: RybexProject["d5oPhase"],
  owner: string,
  approver: string,
  status: string,
  nextRequiredAction: string,
  artifacts: GateArtifact[]
): RybexProject["gate"] => ({
  id: `${projectId}-gate`,
  phaseId,
  name: d5oPhaseMap[phaseId].gateName,
  owner,
  approver,
  readinessPercent: readiness(artifacts),
  status,
  nextRequiredAction,
  artifacts
});

