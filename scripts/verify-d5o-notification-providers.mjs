import assert from "node:assert/strict";
import { registerHooks } from "node:module";
import path from "node:path";
import { pathToFileURL } from "node:url";

const root = process.cwd();
registerHooks({ resolve(specifier, context, nextResolve) {
  if (specifier === "server-only") return { url: "data:text/javascript,export%20%7B%7D", shortCircuit: true };
  if (specifier === "./notification-settings") return nextResolve(pathToFileURL(path.join(root, "lib/d5o/scheduling/notification-settings.ts")).href, context);
  return nextResolve(specifier, context);
} });
process.env.D5O_RESEND_API_KEY = "test-only-key";
process.env.D5O_EMAIL_FROM = "D5O <test@example.org>";
process.env.D5O_TWILIO_ACCOUNT_SID = "ACtest-only";
process.env.D5O_TWILIO_AUTH_TOKEN = "test-only-token";
process.env.D5O_TWILIO_MESSAGING_SERVICE_SID = "MGtest-only";
const calls = [];
globalThis.fetch = async (url, options) => { calls.push({ url: String(url), options }); return new Response("{}", { status: 200 }); };
const { sendScheduleEmail, sendScheduleSms } = await import(pathToFileURL(path.join(root, "lib/d5o/scheduling/notification-providers.ts")).href);
const webPush = (await import("web-push")).default;
const keys = webPush.generateVAPIDKeys();
process.env.D5O_VAPID_PUBLIC_KEY = keys.publicKey;
process.env.D5O_VAPID_PRIVATE_KEY = keys.privateKey;
process.env.D5O_VAPID_SUBJECT = "mailto:test@example.org";
const pushCalls = [];
webPush.sendNotification = async (...args) => { pushCalls.push(args); return { statusCode: 201 }; };
const { sendSchedulePush } = await import(pathToFileURL(path.join(root, "lib/d5o/scheduling/notification-providers.ts")).href);
await sendScheduleEmail("verified@example.org", "event-123", "changed");
await sendScheduleSms("+15555550123", "cancelled");
await sendSchedulePush({ endpoint: "https://fcm.googleapis.com/fcm/send/synthetic", keys: { p256dh: "A".repeat(87), auth: "B".repeat(22) } }, "changed");
assert.equal(calls.length, 2);
assert.equal(calls[0].url, "https://api.resend.com/emails");
assert.equal(calls[0].options.headers["Idempotency-Key"], "event-123");
const email = JSON.parse(calls[0].options.body);
assert.deepEqual(email.to, ["verified@example.org"]);
assert.match(email.text, /accept or decline/);
assert.doesNotMatch(email.text, /North Campus|Rybex|Rotork|customer|site name/i);
assert.match(calls[1].url, /^https:\/\/api\.twilio\.com\/2010-04-01\/Accounts\/ACtest-only\/Messages\.json$/);
const sms = new URLSearchParams(calls[1].options.body);
assert.equal(sms.get("To"), "+15555550123");
assert.match(sms.get("Body"), /cancelled/);
assert.doesNotMatch(sms.get("Body"), /North Campus|Rybex|Rotork/i);
assert.equal(pushCalls.length, 1);
assert.equal(JSON.parse(pushCalls[0][1]).url, "/work/my-schedule");
assert.match(JSON.parse(pushCalls[0][1]).body, /review and respond/);
console.log("Notification provider contracts: PASS — email, SMS and push payloads, idempotent email key, cancellation wording, no work details; network fully stubbed.");
